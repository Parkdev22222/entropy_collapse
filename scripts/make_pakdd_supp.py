"""Build paper/pakdd_supp.tex from paper/steerf.tex: the definitions the
appendix leans on, restated, followed by the appendix verbatim. References to
results that now live in the PAKDD main paper resolve against pakdd.aux."""
import re
import sys
from pathlib import Path

root = sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).resolve().parents[1])
s = open(f"{root}/paper/steerf.tex").read()

pre_end = s.index(r"\begin{document}")
pre = s[:pre_end]
pre = pre.replace(r"\usepackage[review]{acl}",
                  "\\usepackage[margin=1in]{geometry}\n\\usepackage[round]{natbib}\n"
                  "\\usepackage[hidelinks]{hyperref}\n\\usepackage{xr-hyper}\n"
                  "\\externaldocument[M-]{pakdd}")
pre = re.sub(r"\\title\{.*?\}\n\n\\author\{[^}]*\}",
             r"\\title{Supplementary Material\\\\ Where Does Entropy Collapse Go?}\n\n\\author{Anonymous}\n\\date{}",
             pre, flags=re.S)
assert "Supplementary Material" in pre

def cut(a, b):
    i = s.index(a); j = s.index(b, i)
    return s[i:j]

notation = cut(r"\paragraph{Notation.}", r"\paragraph{Entropy collapse in RLVR.}")
channels = cut(r"\section{Two Channels}", r"\section{Experimental Setup}")
channels = channels.replace(r"\section{Two Channels}", r"\subsection{Two channels}") \
                   .replace(r"\subsection{Why the local channel cannot be repaired}",
                            r"\subsubsection{Why the local channel cannot be repaired}") \
                   .replace(r"\section{Estimating the Visitation Channel}",
                            r"\subsection{Estimating the visitation channel}")
appendix = s[s.index(r"\appendix") + len(r"\appendix"): s.index(r"\end{document}")]

# Main-body results that the PAKDD paper now carries.
MAP = {"sec:res:decomp": "sec:decomp", "sec:results": "sec:decomp",
       "sec:res:entropy": "sec:dissoc", "sec:res:acc": "sec:dissoc",
       "sec:setup": "sec:dissoc", "sec:intro": "sec:intro", "sec:prelim": "sec:prelim",
       "sec:conclusion": "sec:conclusion", "tab:decomp": "tab:decomp",
       "tab:decompsec": "tab:decompsec", "tab:entropy": "tab:entropy",
       "tab:arms": "tab:arms", "fig:branch": "fig:branch"}
def remap(t):
    for a, b in MAP.items():
        t = t.replace(r"\ref{" + a + "}", r"\mref{" + b + "}")
    return t

body = (r"""
\begin{document}
\maketitle

\noindent This document accompanies the main paper. Sections and tables marked
``(main paper)'' refer to it; everything else is numbered here. Section~\ref{sec:restated}
restates the definitions and the estimator from an extended version of the text, because
the derivations below refer to them; the remaining sections are the extended version's
appendices. Every number is a macro written by the analysis scripts from the logs.

\section{Definitions and Estimator}
\label{sec:restated}
""" + notation + channels + r"\appendix" + "\n" + appendix +
        "\n\\bibliographystyle{acl_natbib}\n\\bibliography{custom}\n\\end{document}\n")
body = remap(body)
old = r"Sections~\mref{sec:prelim}--\ref{sec:ahdef} state in brief."
assert old in body
body = body.replace(old, r"Section~\ref{sec:restated} states in brief.")
body = body.replace(r"\texttt{actor/entropy}", r"\texttt{actor/\allowbreak entropy}")
pre += "\\emergencystretch=1em\n"
pre += "\\newcommand{\\mref}[1]{\\ref{M-#1} (main paper)}\n"
for k in ("numbers-decomp.tex",):
    if k not in pre:
        pre += f"\\loadnumbers{{{k}}}\n"
out = ("% generated by scripts/make_pakdd_supp.py from paper/steerf.tex -- do not edit;\n"
       "% the appendix is verbatim, references to the main paper resolve via pakdd.aux\n"
       + pre + body)
open(f"{root}/paper/pakdd_supp.tex", "w").write(out)
print(f"wrote {root}/paper/pakdd_supp.tex ({len(out)} bytes)")
